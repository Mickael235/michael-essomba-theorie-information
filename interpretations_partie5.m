function interpretations_partie5()
fprintf('\n=== PARTIE 5 - MODULATION QPSK ===\n');

fprintf('\nQ1-Q2 - Mapping et validation\n');
fprintf(['Le mapping Gray place les symboles en (+/-1/sqrt(2), +/-1/sqrt(2)) avec un seul ', ...
    'bit différent entre voisins. Es=1 donne Eb=0.5. La QPSK revient à deux BPSK ', ...
    'indépendantes sur I et Q ; sans bruit, le modulateur/démodulateur restitue les bits.\n']);

fprintf('\nQ3 - Constellations\n');
fprintf(['À 0 dB les quatre nuages se recouvrent fortement ; à 5 dB ils sont distincts ; ', ...
    'à 10 dB les amas sont compacts et bien séparés. La probabilité d''erreur diminue ', ...
    'donc avec Eb/N0.\n']);

fprintf('\nQ4 - QPSK vs chaîne binaire\n');
fprintf(['À Eb/N0 égal, la QPSK Gray possède le même TEB théorique que la BPSK : ', ...
    'Q(sqrt(2Eb/N0)). Elle transporte cependant 2 bits par symbole ; à durée symbole ', ...
    'égale le débit double, et à débit binaire égal l''occupation spectrale diminue.\n']);

fprintf('\nQ5 - Gray vs naturel\n');
fprintf(['Le mapping naturel donne un TEB supérieur au Gray car une erreur vers un voisin ', ...
    'peut modifier deux bits, contre généralement un seul en Gray. La géométrie de ', ...
    'la constellation reste pourtant identique.\n']);

fprintf('\nQ6 - Hamming + QPSK\n');
fprintf(['Aucun bourrage n''est nécessaire : deux mots Hamming donnent 14 bits, donc ', ...
    'exactement 7 symboles QPSK. Avec Tc=4Tb/7, Ts=8Tb/7=1.1429 pour Tb=1. ', ...
    'La chaîne codée retrouve le comportement de la Partie 4 : pénalité aux faibles ', ...
    'SNR puis avantage du codage lorsque Eb/N0 augmente.\n']);

fprintf(['Aux forts Eb/N0, quelques croisements ponctuels entre les courbes peuvent ', ...
    'apparaître car le nombre d''erreurs observées devient trop faible pour obtenir ', ...
    'une estimation statistique fiable du TEB.\n']);

end