    'répétitions ignorées par un modèle sans mémoire. Les fichiers courts sont ', ...
    'moins bien compressés à cause des surcoûts et d''une statistique moins stable.\n']);

fprintf('\nQ9 - Sortie Huffman\n');
fprintf(['Un bon codeur de source produit des bits presque équiprobables et peu dépendants. ', ...
