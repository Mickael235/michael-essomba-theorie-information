% Commentaires correspondant aux résultats de la Partie 6.

if exist('resultats_partie6.mat','file')
    r = load('resultats_partie6.mat');

    i6 = find(r.EbN0_vec == 6,1);

    if ~isempty(i6)
        fprintf('\n--- Résultats à Eb/N0 = 6 dB, chaîne A ---\n');

        for c = 1:size(r.cfg,1)
            fprintf('%-16s TEB = %.3e\n', ...
                r.cfg{c,1},r.tebA(c,i6));
        end

        fprintf(['Dégradation due au décalage T/4 : ', ...
            'alpha=0.22 -> x%.1f ; alpha=1 -> x%.1f\n'], ...
            r.tebA(3,i6)/r.tebA(2,i6), ...
            r.tebA(5,i6)/r.tebA(4,i6));
    end
end


%% Q1 - Filtre porte

fprintf('\nQ1 - Filtre porte\n');

fprintf(['Le filtre porte suivi de son filtre adapté réalise le même principe ', ...
    'que le détecteur optimal étudié dans la Partie 3. Après filtrage, ', ...
    'l''échantillon prélevé à l''instant optimal rassemble l''énergie des ', ...
    'L échantillons du symbole. Les résultats montrent que le TEB obtenu ', ...
    'avec le filtre porte reste pratiquement confondu avec la théorie ', ...
    'Q(sqrt(2Eb/N0)).\n']);


%% Q2 - Filtre RRC

fprintf('\nQ2 - Filtre RRC\n');

fprintf(['Le filtre racine de cosinus surélevé est tronqué sur 10 symboles ', ...
    'et normalisé à énergie unité. Les réponses obtenues pour alpha=0.22, ', ...
    'alpha=0.35 et alpha=1 montrent que le facteur de retombée modifie ', ...
    'la forme temporelle du filtre. Lorsque alpha augmente, la réponse ', ...
    'est davantage concentrée dans le temps mais occupe une bande ', ...
    'fréquentielle plus importante.\n']);

fprintf(['Les singularités apparentes de la formule sont traitées par passage à la limite. ', ...
    'On obtient h(0)=(1-alpha+4*alpha/pi)/sqrt(T), et en t=+/-T/(4*alpha), ', ...
    'une valeur finie donnée par la limite analytique. Ces deux cas particuliers ', ...
    'sont directement traités dans rrc_perso.m afin d''éviter une division par zéro.\n']);

%% Q3 - Critère de Nyquist

fprintf('\nQ3 - h et h*h\n');

fprintf(['Le filtre RRC seul ne s''annule pas nécessairement aux multiples ', ...
    'de la durée symbole T. En revanche, la convolution h*h correspond ', ...
    'au filtre global en cosinus surélevé. Les figures montrent que cette ', ...
    'réponse vaut environ 1 à t=0 et s''annule aux multiples non nuls de T. ', ...
    'L''interférence entre symboles est donc nulle aux instants optimaux ', ...
    'd''échantillonnage. Les très faibles valeurs résiduelles proviennent ', ...
    'principalement de la troncature du filtre à 10 symboles.\n']);


%% Q4 - Occupation spectrale

fprintf('\nQ4 - Occupation spectrale\n');

fprintf(['Le filtre porte présente des lobes secondaires importants et une ', ...
    'décroissance spectrale lente. Le RRC concentre beaucoup mieux ', ...
    'l''énergie dans la bande utile. Sa bande théorique vaut ', ...
    '(1+alpha)/(2T). Ainsi alpha=0.22 conduit à environ 0.61/T, ', ...
    'alors que alpha=1 conduit à 1/T. Une faible valeur de alpha ', ...
    'est donc avantageuse pour l''occupation spectrale, au prix d''une ', ...
    'plus grande sensibilité aux erreurs de synchronisation.\n']);


%% Q5 - Chaîne complète

fprintf('\nQ5 - Chaîne complète\n');

fprintf(['À l''instant optimal d''échantillonnage, les chaînes avec filtre ', ...
    'porte et filtre RRC donnent pratiquement le même TEB que la chaîne ', ...
    'QPSK précédente. Par exemple à 6 dB, les TEB de la chaîne A sont ', ...
    'de l''ordre de 2e-3 pour les trois filtrages. Le filtre adapté ', ...
    'récupère l''énergie du symbole sans introduire de pénalité notable ', ...
    'en Eb/N0. L''apport principal du RRC concerne donc la maîtrise de ', ...
    'l''interférence entre symboles et de l''occupation spectrale.\n']);

fprintf(['La chaîne avec codage de Hamming présente la même tendance que ', ...
    'dans les parties précédentes : elle peut être pénalisée aux faibles ', ...
    'Eb/N0 mais devient intéressante lorsque le bruit diminue, car le ', ...
    'décodeur corrige les erreurs simples.\n']);


%% Q6 - Décalage T/4

fprintf('\nQ6 - Décalage T/4\n');

fprintf(['Lorsque l''instant d''échantillonnage est décalé de T/4, le ', ...
    'récepteur ne prélève plus le signal au point où l''IES est nulle. ', ...
    'La constellation se disperse et le diagramme de l''œil montre que ', ...
    'la marge temporelle de décision diminue fortement. Cette dégradation ', ...
    'est visible même sans bruit : elle provient donc bien de l''IES et ', ...
    'de l''erreur de synchronisation, et non du canal AWGN.\n']);

fprintf(['Les résultats montrent clairement que alpha=1 est plus robuste au ', ...
    'décalage temporel que alpha=0.22. À 6 dB, pour la chaîne A, le TEB ', ...
    'passe de 2.14e-3 à 3.97e-2 avec alpha=0.22, soit une dégradation ', ...
    'd''environ x18.5. Avec alpha=1, il passe de 2.19e-3 à 1.50e-2, ', ...
    'soit environ x6.8. Le diagramme de l''œil confirme que alpha=1 ', ...
    'présente une ouverture temporelle plus large.\n']);

fprintf(['Il existe donc un compromis : alpha=0.22 réduit l''occupation ', ...
    'spectrale, tandis que alpha=1 occupe davantage de bande mais offre ', ...
    'une meilleure tolérance aux erreurs de synchronisation.\n']);


%% Hamming

fprintf('\nEffet du codage Hamming\n');

fprintf(['Le codage Hamming conserve les mêmes tendances vis-à-vis du ', ...
    'filtrage et du décalage temporel. Lorsque les erreurs restent ', ...
    'isolées, le décodeur peut les corriger. Lorsque le décalage T/4 ', ...
    'provoque beaucoup d''erreurs, plusieurs bits d''un même mot-code ', ...
    'peuvent être faux et le code Hamming C(7,4), limité à la correction ', ...
    'd''une erreur par mot, perd progressivement son efficacité.\n']);