fprintf('\n=== PARTIE 4 - CODAGE HAMMING C(7,4) ===\n');

fprintf('\nQ1-Q6 - Construction et validation\n');
fprintf(['Le code C(7,4) est systématique, vérifie G*H''=0 et a une distance minimale dmin=3 : ', ...
    'les colonnes de H sont non nulles et distinctes, donc la somme de deux colonnes n''est jamais nulle. ', ...
    'Avec dmin=3, il corrige toute erreur simple OU détecte deux erreurs (pas les deux à la fois). ', ...
    'Pour une erreur simple, le syndrome est égal à la colonne de H de la position fautive, ', ...
    'ce qui permet la correction. Le codeur/décodeur Matlab sert de référence aux blocs Simulink ; ', ...
    'le codeur à registre à décalage reproduit les 16 mots-codes du produit matriciel.\n']);

fprintf('\nQ7-Q9 - Performances théoriques\n');
fprintf(['Le rendement vaut R=4/7. À énergie par bit utile Eb fixée, chaque bit codé reçoit ', ...
    'Ec=(4/7)Eb, donc p=Q(sqrt(2*(4/7)*Eb/N0)). Comparer à variance de bruit égale sans tenir ', ...
    'compte de R est trompeur : on donnerait à chaque bit codé la même énergie qu''à un bit non codé, ', ...
    'soit 7/4 d''énergie par bit utile, et on attribuerait au code un gain qui vient en réalité de ', ...
    'cette énergie supplémentaire. ', ...
    'L''approximation de Q8 (facteur j/7) est optimiste : avec deux erreurs, le syndrome désigne ', ...
    'une troisième position et le décodeur « corrige » à tort, ce qui laisse 3 erreurs dans le mot, ', ...
    'soit 12/7 en moyenne sur les 4 bits utiles. Le terme d''ordre 2 vaut donc 9p^2 et non 6p^2 : ', ...
    'le TEB réel est environ 1,5 fois plus grand à fort SNR.\n']);

fprintf('\nQ10 - Théorie et simulation\n');
fprintf(['La simulation suit la théorie exacte après décodage (formule obtenue par énumération des ', ...
    'motifs d''erreur) : 0 dB -> 1.18e-1 simulé contre 1.19e-1 ; 5 dB -> 7.0e-3 contre 6.8e-3 ; ', ...
    '6 dB -> 2.1e-3 contre 2.3e-3. Les écarts restent compatibles avec les fluctuations ', ...
    'statistiques (350 erreurs à 5 dB). À fort SNR, le nombre d''erreurs est trop faible pour conclure ', ...
    'avec 5e4 bits : 8 erreurs à 8 dB, aucune à 9 dB (théorie 1.5e-5) ; il faudrait ~1e6 bits, ', ...
    'comme l''indique l''énoncé. Les limites de Shannon (0,24 dB pour R=4/7 ; -1,59 dB pour la limite ', ...
    'absolue) sont très à gauche des courbes : Hamming en reste loin.\n']);

fprintf('\nQ11 - Gain de codage\n');
fprintf(['Le codage devient avantageux à partir de 5,85 dB (théorie) ; la simulation le confirme : ', ...
    'à 5 dB Hamming est moins bon (7.0e-3 contre 6.0e-3), à 6 dB il est meilleur. En dessous, la ', ...
    'perte d''énergie par bit codé (10 log10(4/7) = -2,4 dB) n''est pas compensée par la correction ', ...
    'd''une seule erreur par mot. Pour un TEB de 1e-4, il faut 8,398 dB sans codage et 8,084 dB ', ...
    'avec Hamming : gain de codage de 0,314 dB (résultat théorique, non mesurable avec 5e4 bits). ', ...
    'Par rapport à la limite de Shannon pour R=4/7 (0,24 dB), il reste environ 7,8 dB d''écart : ', ...
    'Hamming (7,4) corrige une erreur par mot en décision dure et exploite mal la capacité du canal. ', ...
    'Des codes plus longs ou itératifs (BCH, LDPC, turbo) s''en approchent beaucoup plus.\n']);

fprintf('\nQ12 - Débit et latence\n');
fprintf(['À débit utile constant, le débit canal est multiplié par 7/4 (+75 %%), donc, à modulation ', ...
    'inchangée, la bande occupée augmente aussi de 75 %%. En temps réel, la latence est de ~8 Tb : ', ...
    '4 Tb pour regrouper 4 bits à l''encodage et 7 Tc = 4 Tb pour recevoir le mot avant décodage. ', ...
    'Le retard mesuré en simulation (4 bits) correspond à l''attente du Buffer ; la durée de ', ...
    'transmission du mot n''est pas modélisée.\n']);

fprintf('\nComplément\n');
fprintf('Le décodeur à registre de Meggitt (complément de Q6) n''a pas été réalisé.\n');
end